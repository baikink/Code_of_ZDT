/**
  * @file    ball_balance.h
  * @brief   钢球平衡双环控制 —— 参数和接口
  *
  * ========== 物理原理（一句话） ==========
  * 钢球在倾斜的凹槽里受重力滚动。
  * 球位置：正值(+)=球在左边，负值(-)=球在右边（视觉反馈的坐标方向）
  * 摆杆上升(CW)，摆杆下降(CCW)，控制倾角 = 控制球的加速度。
  *
  * ========== 控制原理 ==========
  * 两个 PID 环同时工作，输出相加：
  *
  *   环1（位置环）：球偏了多少 → 产生一个脉冲，把球"推"回去
  *      例：球在左边 +5cm → 误差=0−(+5)=−5 → 算出负脉冲 → 摆杆下降 → 球往右回中
  *
  *   环2（速度环）：球在运动吗 → 产生一个反向脉冲，给球"刹车"
  *      例：球正往左边滚(正速度) → 误差=0−正=负 → 算出负脉冲 → 摆杆下降 → 减速
  *
  *   总脉冲 = 环1输出 + 环2输出，限幅 ±300 保证安全
  *
  * ========== 方向约定（位置符号由视觉决定） ==========
  * 球位置：正值(+)=球在左边，负值(-)=球在右边
  * 正脉冲(+) = CW  = 摆杆上升
  * 负脉冲(-) = CCW = 摆杆下降
  */
#ifndef __BALL_BALANCE_H
#define __BALL_BALANCE_H

#include <stdint.h>

/* ── 电机参数 ── */
#define BALL_MOTOR_ADDR   1       /* 电机地址 */
#define BALL_MOTOR_VEL    1500    /* 运动速度 RPM */
#define BALL_MOTOR_ACC    100     /* 加速度档位(0=直接启动) */

/* ── 安全限幅（绝对不能超！超出可能撞机械限位）── */
#define MAX_PULSE_CW      300     /* CW 方向最多 300 脉冲 */
#define MAX_PULSE_CCW    -300     /* CCW 方向最多 300 脉冲 */

/* ══════════════════════════════════════════════════════
 * PID 参数 —— 当前全 0（空跑，电机不动）
 * 调参时在这里改数值，改完重新编译烧录即可
 * ══════════════════════════════════════════════════════ */

/* 环1 位置环：位置误差(cm) → 驱动脉冲 */
#define POS_KP  5.0f       /* 比例：球偏离 1cm 产生多少脉冲 */
#define POS_KI  0.0f       /* 积分：消除静差，让球精确停在目标点 */
#define POS_KD  0.0f       /* 微分：球快到了提前减速（预测） */

/* 环2 速度环：球速度(cm/s) → 阻尼脉冲（目标速度固定为 0） */
#define SPD_KP  5.0f       /* 比例：球速度 1cm/s 产生多少反向脉冲 */
#define SPD_KI  0.0f       /* 积分：一般不用，保持 0 */
#define SPD_KD  0.0f       /* 微分：一般不用，保持 0 */

/* ── 函数声明 ── */
void ball_balance_init(void);
void ball_balance_control(float target_cm);

/* ── 调试变量（VOFA 显示用）── */
extern float  dbg_target_cm;     /* 环1 目标位置(cm) */
extern float  dbg_speed_out;     /* 环2 速度环输出(脉冲) */
extern int32_t dbg_total_pulses; /* 总输出脉冲 */

#endif
