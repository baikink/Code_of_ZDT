/**
 * ============================================================================
 * 文件名称：UART_Tuning.h
 * 功能描述：UART在线调参模块 - 支持手机App和串口助手两种调参方式
 *
 * 通信协议：
 *   ┌─────────────────────────────────────────────────────────────┐
 *   │  【滑杆数据包】用于PID参数实时调节                          │
 *   │  格式：[slider,参数名,值]                                  │
 *   │  示例：[slider,ukp,-165.000]                              │
 *   │  支持：ukp/uki/ukd(直立) vkp/vki/vkd(速度)                │
 *   │        tkp/tki/tkd(转向) mb(机械中值)                     │
 *   ├─────────────────────────────────────────────────────────────┤
 *   │  【摇杆数据包】用于小车运动控制                             │
 *   │  格式：[joystick,name,LV,RH,extra]                        │
 *   │        LV = 左摇杆垂直方向(-128~+127，控制速度)            │
 *   │        RH = 右摇杆水平方向(-128~+127，控制转向)            │
 *   │  示例：[joystick,1,50,0,0] → 前进                         │
 *   │        [joystick,1,0,-30,0] → 右转                        │
 *   ├─────────────────────────────────────────────────────────────┤
 *   │  【文本命令】用于串口助手调试                               │
 *   │  格式：命令# 或 [命令]                                     │
 *   │  示例：ukp-165#  GET_PID  HELP  RESET                      │
 *   └─────────────────────────────────────────────────────────────┘
 *
 * 使用流程：
 *   1. 调用 UART_Tuning_Init() 初始化UART中断
 *   2. 在主循环中调用 UART_Tuning_Task() 处理接收到的命令
 *   3. 手机App通过蓝牙/WiFi发送滑杆或摇杆数据
 * ============================================================================
 */

#ifndef __UART_TUNING_H__
#define __UART_TUNING_H__

#include "ti_msp_dl_config.h"
#include "Balance_Car/Balance_Car_PID.h"

/* ============================================================================
 * 配置宏定义
 * ============================================================================ */

/** UART接收缓冲区大小（字节）
 *  需要足够容纳最长的数据包，如：[slider,ukp,-165.000] = 20字节 */
#define UART_TUNING_RX_BUFFER_SIZE   64

/* ============================================================================
 * 函数声明
 * ============================================================================ */

/**
 * 初始化UART调参模块
 * 功能：配置接收缓冲区、使能UART中断
 * 调用时机：系统启动时调用一次
 */
void UART_Tuning_Init(void);

/**
 * UART调参任务处理函数
 * 功能：从命令队列取出并解析执行一条命令
 * 调用时机：在主循环中周期性调用（建议每10ms一次）
 * 说明：非阻塞设计，无命令时立即返回
 */
void UART_Tuning_Task(void);

/**
 * 发送字符串到UART（不带换行）
 * @param str 要发送的字符串
 */
void UART_Tuning_SendString(const char *str);

/**
 * 发送字符串到UART（带\r\n换行）
 * @param str 要发送的字符串
 */
void UART_Tuning_SendLine(const char *str);

#endif
